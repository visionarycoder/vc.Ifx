    [TestMethod]
    [DataRow("/orders", "/ORDERS/")]
    [DataRow("/orders/{id}", "/orders/{other}")]
    [DataRow("/orders/{id:int}", "/orders/{other:int}")]
    [DataRow("/files/{*path}", "/files/{**other}")]
    public void DuplicateOrEquivalentRoutesRejectEveryParticipant(string first, string second)
    {
        var result = Run($"internal static class H {{ [GenerateEndpoint(\"{first}\", \"GET\")] public static string A() => \"a\"; [GenerateEndpoint(\"{second}\", \"get\")] public static string B() => \"b\"; }}");
        result.Diagnostics.Should().HaveCount(2).And.OnlyContain(d => d.Id == "IFX2002" && d.AdditionalLocations.Count == 1);
        result.Source.Should().NotContain("global::H.A").And.NotContain("global::H.B");
    }

    [TestMethod]
    public void DifferentVerbsShareRouteButDuplicateNamesFail()
