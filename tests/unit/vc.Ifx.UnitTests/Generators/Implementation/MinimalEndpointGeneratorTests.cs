        result.Diagnostics.Should().HaveCount(2).And.OnlyContain(d => d.Id == "IFX2003");
    }

    [TestMethod]
    public void EmptyAndMissingHostCasesAreExplicit()
    {
        Run("internal class H { }").AssertCompiles();
        GeneratorHarness.Run(Header + "internal class H { }", new MinimalEndpointGenerator(), hosting: false).Source.Should().BeEmpty();
        var result = GeneratorHarness.Run(Header + "internal class H { [GenerateEndpoint(\"/\", \"GET\")] public static string Read() => \"ok\"; }", new MinimalEndpointGenerator(), hosting: false);
        AssertDiagnostic(result, "IFX2005");
        result.Source.Should().BeEmpty();
    }

