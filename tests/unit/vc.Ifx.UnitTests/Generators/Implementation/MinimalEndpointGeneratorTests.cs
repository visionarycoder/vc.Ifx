    public void IncompatibleMarkerMetadataIsDiagnosedWithoutCrashing(string option)
    {
        var result = GeneratorHarness.Run(Header + $$"""
            namespace vc.Ifx.Generators.Abstractions.Attributes
            {
                public sealed class GenerateEndpointAttribute(string route, string method) : Attribute
                {
                    public object Name { get; set; } = "";
                    public object RequireAuthorization { get; set; } = false;
                    public object Tags { get; set; } = "";
                }
            }
            internal static class H { [GenerateEndpoint("/", "GET", {{option}})] public static string Read() => "ok"; }
            """, new MinimalEndpointGenerator(), includeAttributes: false);
        AssertDiagnostic(result, "IFX2000");
        result.Source.Should().NotContain("global::H.Read");
    }

    [TestMethod]
    public void CustomAwaitableAndDelegateArrayAreRejected()
    {
        AssertDiagnostic(Run("internal static class H { [GenerateEndpoint(\"/\", \"GET\")] public static string Read(this string value) => value; }"), "IFX2001");
        AssertDiagnostic(Run("internal class Awaitable { public int GetAwaiter() => 1; } internal static class H { [GenerateEndpoint(\"/\", \"GET\")] public static Awaitable Read() => new(); }"), "IFX2001");
        AssertDiagnostic(Run("internal static class H { [GenerateEndpoint(\"/\", \"GET\")] public static Func<int>[] Read() => new Func<int>[0]; }"), "IFX2006");
    }

    private static GeneratorHarness.Result Run(string source) => GeneratorHarness.Run(Header + source, new MinimalEndpointGenerator());
    private static void AssertDiagnostic(GeneratorHarness.Result result, string id)
    {
        result.Diagnostics.Should().Contain(d => d.Id == id && d.Severity == DiagnosticSeverity.Error && d.Location.IsInSource);
    }
