    private const string Header = "using System; using System.Threading; using System.Threading.Tasks; using vc.Ifx.Generators.Abstractions.Attributes; ";

    [TestMethod]
    public void SimpleRegistryMatchesGoldenSourceAndCompiles()
    {
        var result = Run("internal static class Handlers { [GenerateEndpoint(\"/health\", \"get\")] internal static string Read() => \"healthy\"; }");
        result.AssertCompiles();
        result.Source.Should().Be("""
            // <auto-generated />
            #nullable enable
            namespace vc.Ifx.Generated;

            internal static class IfxEndpointRouteBuilderExtensions
            {
                public static global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder MapGeneratedIfxEndpoints(this global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder endpoints)
                {
                    global::System.ArgumentNullException.ThrowIfNull(endpoints);
                    {
                        var endpoint = global::Microsoft.AspNetCore.Builder.EndpointRouteBuilderExtensions.MapMethods(endpoints, "/health", new string[] { "GET" }, (global::System.Delegate)global::Handlers.Read);
                    }
                    return endpoints;
                }
            }

            """.Replace("\r\n", "\n"));
    }

