    [TestMethod]
    public void ReorderingInputAndChangingUnrelatedSyntaxKeepsOutputStable()
    {
        const string first = "internal static class A { [GenerateEndpoint(\"/z\", \"GET\")] public static string Read() => \"ok\"; }";
        const string second = "internal static class B { [GenerateEndpoint(\"/a\", \"GET\")] public static string Read() => \"ok\"; }";
        var initial = Run(first + second);
        Run(second + first).Source.Should().Be(initial.Source);
        var compilation = GeneratorHarness.Compilation(Header + first + second).AddSyntaxTrees(CSharpSyntaxTree.ParseText("internal class Unrelated { }", GeneratorHarness.ParseOptions));
        var updated = GeneratorHarness.Run(compilation, initial.Driver);
        updated.Source.Should().Be(initial.Source);
        updated.Run.Results[0].TrackedSteps["EndpointSource"].SelectMany(step => step.Outputs).Should().OnlyContain(output => output.Reason == IncrementalStepRunReason.Cached || output.Reason == IncrementalStepRunReason.Unchanged);
    }

    [TestMethod]
    public void CancellationIsPropagated()
    {
        using var cancellation = new CancellationTokenSource();
        cancellation.Cancel();
        Action run = () => GeneratorHarness.Run(Header + "internal class H { }", new MinimalEndpointGenerator(), cancellationToken: cancellation.Token);
        run.Should().Throw<OperationCanceledException>();
    }

