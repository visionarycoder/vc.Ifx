    [TestMethod]
    public void AllMetadataEmitsInStableOrderAndCompiles()
    {
        var result = Run("internal static class H { [GenerateEndpoint(\"/\", \"PATCH\", Name=\"Edit\", Summary=\"Title\\nnext\", Description=\"Detail\", Tags=new string[]{\"One\",\"One\",\"Two\"}, RequireAuthorization=true, AuthorizationPolicy=\"Edit\", ExcludeFromDescription=true)] public static string Read() => \"ok\"; }");
        result.AssertCompiles();
        result.Source.Should().Contain("new string[] { \"One\", \"Two\" }");
        var calls = new[] { ".WithName(", ".WithSummary(", ".WithDescription(", ".WithTags(", ".RequireAuthorization(", ".ExcludeFromDescription(" };
        calls.Select(call => result.Source.IndexOf(call, StringComparison.Ordinal)).Should().BeInAscendingOrder();
    }

