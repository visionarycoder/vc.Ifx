using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace vc.Ifx.Generators;

[Generator(LanguageNames.CSharp)]
public sealed class InterceptorsGenerator : IIncrementalGenerator
{
    private const string AttributeFullName = GeneratorConstants.GenerateInterceptorsAttributeAbstractionsFullName;
    private const string ServiceRequestFullName = GeneratorConstants.ServiceRequestFullName;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttributeFullName,
                (node, _) => node is ClassDeclarationSyntax,
                BuildRequest)
            .Where(request => request != null);

        context.RegisterSourceOutput(candidates, (ctx, request) => Emit(ctx, request!));
    }

    private static GenerationRequest? BuildRequest(GeneratorAttributeSyntaxContext context, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var targetType = (INamedTypeSymbol)context.TargetSymbol;
        var attribute = context.Attributes[0];
        var activitySourceName = ReadConstructorString(attribute, 0);

        if (string.IsNullOrWhiteSpace(activitySourceName))
        {
            activitySourceName = targetType.ToDisplayString();
        }

        var interceptorSuffix = ReadNamedString(attribute, "InterceptorSuffix");
        if (string.IsNullOrWhiteSpace(interceptorSuffix))
        {
            interceptorSuffix = ReadNamedString(attribute, "DecoratorSuffix");
        }

        if (string.IsNullOrWhiteSpace(interceptorSuffix))
        {
            interceptorSuffix = "OpenTelemetryInterceptor";
        }

        var interfaces = ReadServiceTypes(attribute)
            .Where(symbol => symbol.TypeKind == TypeKind.Interface)
            .GroupBy(symbol => symbol.ToDisplayString(), StringComparer.Ordinal)
            .Select(group => group.First())
            .ToImmutableArray();

        if (interfaces.Length == 0)
        {
            return null;
        }

        return new GenerationRequest(
            targetType.ContainingNamespace.IsGlobalNamespace ? string.Empty : targetType.ContainingNamespace.ToDisplayString(),
            targetType.Name,
            activitySourceName!,
            interceptorSuffix!,
            interfaces);
    }

    private static string? ReadConstructorString(AttributeData attribute, int index)
    {
        if (attribute.ConstructorArguments.Length <= index)
        {
            return null;
        }

        return attribute.ConstructorArguments[index].Value as string;
    }

    private static string? ReadNamedString(AttributeData attribute, string name)
    {
        foreach (var named in attribute.NamedArguments)
        {
            if (named.Key == name)
            {
                return named.Value.Value as string;
            }
        }

        return null;
    }

    private static IEnumerable<INamedTypeSymbol> ReadServiceTypes(AttributeData attribute)
    {
        if (attribute.ConstructorArguments.Length < 2)
        {
            yield break;
        }

        var typesArgument = attribute.ConstructorArguments[1];

        if (typesArgument.Kind != TypedConstantKind.Array || typesArgument.IsNull)
        {
            yield break;
        }

        foreach (var value in typesArgument.Values)
        {
            if (value.Value is INamedTypeSymbol typeSymbol)
            {
                yield return typeSymbol;
            }
        }
    }

    private static void Emit(SourceProductionContext context, GenerationRequest request)
    {
        var source = GenerateSource(request);
        var hintName = request.TargetNamespace + "." + request.TargetTypeName + ".Interceptors.g.cs";
        context.AddSource(hintName, SourceText.From(source, Encoding.UTF8));
    }

    private static string GenerateSource(GenerationRequest request)
    {
        var builder = new StringBuilder();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("using System;");
        builder.AppendLine("using System.Diagnostics;");
        builder.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        builder.AppendLine("using Microsoft.Extensions.DependencyInjection.Extensions;");
        builder.AppendLine("using Microsoft.Extensions.Logging;");
        builder.AppendLine();

        if (!string.IsNullOrWhiteSpace(request.TargetNamespace))
        {
            builder.Append("namespace ");
            builder.Append(request.TargetNamespace);
            builder.AppendLine();
            builder.AppendLine("{");
        }

        var indent = string.IsNullOrWhiteSpace(request.TargetNamespace) ? string.Empty : "    ";

        builder.Append(indent);
        builder.Append("internal static class ");
        builder.Append(request.TargetTypeName);
        builder.AppendLine("InterceptorsRegistration");
        builder.Append(indent);
        builder.AppendLine("{");

        builder.Append(indent);
        builder.AppendLine("    public static IServiceCollection AddInterceptors(this IServiceCollection services)");
        builder.Append(indent);
        builder.AppendLine("    {");
        builder.Append(indent);
        builder.AppendLine("        if (services == null)");
        builder.Append(indent);
        builder.AppendLine("        {");
        builder.Append(indent);
        builder.AppendLine("            throw new ArgumentNullException(nameof(services));");
        builder.Append(indent);
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.Append(indent);
        builder.Append("        services.TryAddSingleton(new ActivitySource(");
        builder.Append(ToLiteral(request.ActivitySourceName));
        builder.AppendLine("));");

        foreach (var contract in request.Contracts)
        {
            var contractType = contract.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var interceptorType = "global::" + (string.IsNullOrWhiteSpace(request.TargetNamespace) ? string.Empty : request.TargetNamespace + ".") + GetInterceptorName(contract, request.InterceptorSuffix);

            builder.Append(indent);
            builder.Append("        Intercept(services, typeof(");
            builder.Append(contractType);
            builder.Append("), typeof(");
            builder.Append(interceptorType);
            builder.AppendLine("));");
        }

        builder.AppendLine();
        builder.Append(indent);
        builder.AppendLine("        return services;");
        builder.Append(indent);
        builder.AppendLine("    }");
        builder.AppendLine();

        builder.Append(indent);
        builder.AppendLine("    private static void Intercept(IServiceCollection services, Type serviceType, Type interceptorType)");
        builder.Append(indent);
        builder.AppendLine("    {");
        builder.Append(indent);
        builder.AppendLine("        for (var index = services.Count - 1; index >= 0; index--)");
        builder.Append(indent);
        builder.AppendLine("        {");
        builder.Append(indent);
        builder.AppendLine("            var descriptor = services[index];");
        builder.Append(indent);
        builder.AppendLine("            if (descriptor.ServiceType != serviceType)");
        builder.Append(indent);
        builder.AppendLine("            {");
        builder.Append(indent);
        builder.AppendLine("                continue;");
        builder.Append(indent);
        builder.AppendLine("            }");
        builder.AppendLine();
        builder.Append(indent);
        builder.AppendLine("            services.RemoveAt(index);");
        builder.Append(indent);
        builder.AppendLine("            services.Insert(index, ServiceDescriptor.Describe(");
        builder.Append(indent);
        builder.AppendLine("                serviceType,");
        builder.Append(indent);
        builder.AppendLine("                provider =>");
        builder.Append(indent);
        builder.AppendLine("                {");
        builder.Append(indent);
        builder.AppendLine("                    var inner = CreateService(provider, descriptor);");
        builder.Append(indent);
        builder.AppendLine("                    return ActivatorUtilities.CreateInstance(provider, interceptorType, inner);");
        builder.Append(indent);
        builder.AppendLine("                },");
        builder.Append(indent);
        builder.AppendLine("                descriptor.Lifetime));");
        builder.Append(indent);
        builder.AppendLine("            return;");
        builder.Append(indent);
        builder.AppendLine("        }");
        builder.Append(indent);
        builder.AppendLine("    }");
        builder.AppendLine();

        builder.Append(indent);
        builder.AppendLine("    private static object CreateService(IServiceProvider provider, ServiceDescriptor descriptor)");
        builder.Append(indent);
        builder.AppendLine("    {");
        builder.Append(indent);
        builder.AppendLine("        if (descriptor.ImplementationInstance != null)");
        builder.Append(indent);
        builder.AppendLine("        {");
        builder.Append(indent);
        builder.AppendLine("            return descriptor.ImplementationInstance;");
        builder.Append(indent);
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.Append(indent);
        builder.AppendLine("        if (descriptor.ImplementationFactory != null)");
        builder.Append(indent);
        builder.AppendLine("        {");
        builder.Append(indent);
        builder.AppendLine("            return descriptor.ImplementationFactory(provider);");
        builder.Append(indent);
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.Append(indent);
        builder.AppendLine("        if (descriptor.ImplementationType != null)");
        builder.Append(indent);
        builder.AppendLine("        {");
        builder.Append(indent);
        builder.AppendLine("            return ActivatorUtilities.GetServiceOrCreateInstance(provider, descriptor.ImplementationType);");
        builder.Append(indent);
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.Append(indent);
        builder.AppendLine("        throw new InvalidOperationException(\"Unable to resolve service descriptor implementation.\");");
        builder.Append(indent);
        builder.AppendLine("    }");

        builder.Append(indent);
        builder.AppendLine("}");
        builder.AppendLine();

        foreach (var contract in request.Contracts)
        {
            EmitInterceptor(builder, indent, request, contract);
        }

        if (!string.IsNullOrWhiteSpace(request.TargetNamespace))
        {
            builder.AppendLine("}");
        }

        return builder.ToString();
    }

    private static void EmitInterceptor(StringBuilder builder, string indent, GenerationRequest request, INamedTypeSymbol contract)
    {
        var interceptorName = GetInterceptorName(contract, request.InterceptorSuffix);
        var contractType = contract.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        builder.Append(indent);
        builder.AppendLine("/// <summary>");
        builder.Append(indent);
        builder.AppendLine("/// Interceptor that wraps and instruments a service interface with observability.");
        builder.Append(indent);
        builder.AppendLine("/// ");
        builder.Append(indent);
        builder.AppendLine("/// This interceptor implements the same interface as the wrapped service and delegates all calls to it.");
        builder.Append(indent);
        builder.AppendLine("/// It intercepts each method invocation to add cross-cutting concerns:");
        builder.Append(indent);
        builder.AppendLine("/// - Creates an OpenTelemetry Activity with operation name and metadata tags");
        builder.Append(indent);
        builder.AppendLine("/// - Records correlation ID and message ID from ServiceMessage parameters");
        builder.Append(indent);
        builder.AppendLine("/// - Sets activity status (Ok/Error) based on method outcome");
        builder.Append(indent);
        builder.AppendLine("/// - Logs operation details including exceptions");
        builder.Append(indent);
        builder.AppendLine("/// - Ensures ConfigureAwait(false) on async operations");
        builder.Append(indent);
        builder.AppendLine("/// </summary>");
        builder.Append(indent);
        builder.Append("internal sealed class ");
        builder.Append(interceptorName);
        builder.Append(" : ");
        builder.Append(contractType);
        builder.AppendLine();
        builder.Append(indent);
        builder.AppendLine("{");

        builder.Append(indent);
        builder.AppendLine("    /// <summary>The wrapped service instance that receives all method calls after instrumentation.</summary>");
        builder.Append(indent);
        builder.Append("    private readonly ");
        builder.Append(contractType);
        builder.AppendLine(" innerService;");
        builder.Append(indent);
        builder.AppendLine("    /// <summary>ActivitySource used to create and manage OpenTelemetry traces for this interceptor.</summary>");
        builder.Append(indent);
        builder.AppendLine("    private readonly ActivitySource activitySource;");
        builder.Append(indent);
        builder.Append("    /// <summary>Logger used to record structured telemetry and exception details.");
        builder.AppendLine("</summary>");
        builder.Append(indent);
        builder.Append("    private readonly ILogger<");
        builder.Append(interceptorName);
        builder.AppendLine("> logger;");
        builder.AppendLine();

        builder.Append(indent);
        builder.AppendLine("    /// <summary>");
        builder.Append(indent);
        builder.AppendLine("    /// Initializes a new instance of the interceptor.");
        builder.Append(indent);
        builder.AppendLine("    /// </summary>");
        builder.Append(indent);
        builder.AppendLine("    /// <param name=\"inner\">The wrapped service instance that implements the actual business logic.</param>");
        builder.Append(indent);
        builder.AppendLine("    /// <param name=\"activitySource\">OpenTelemetry ActivitySource for creating tracing activities.</param>");
        builder.Append(indent);
        builder.AppendLine("    /// <param name=\"logger\">Logger instance for recording operation telemetry and errors.</param>");
        builder.Append(indent);
        builder.Append("    public ");
        builder.Append(interceptorName);
        builder.Append("(");
        builder.Append(contractType);
        builder.Append(" inner, ActivitySource activitySource, ILogger<");
        builder.Append(interceptorName);
        builder.AppendLine("> logger)");
        builder.Append(indent);
        builder.AppendLine("    {");
        builder.Append(indent);
        builder.AppendLine("        innerService = inner ?? throw new ArgumentNullException(nameof(inner));");
        builder.Append(indent);
        builder.AppendLine("        this.activitySource = activitySource ?? throw new ArgumentNullException(nameof(activitySource));");
        builder.Append(indent);
        builder.AppendLine("        this.logger = logger ?? throw new ArgumentNullException(nameof(logger));");
        builder.Append(indent);
        builder.AppendLine("    }");
        builder.AppendLine();

        foreach (var property in CollectProperties(contract))
        {
            EmitProperty(builder, indent, property, contract.GetMembers(property.Name).Any(member => member.Kind != SymbolKind.Property));
            builder.AppendLine();
        }

        foreach (var eventSymbol in CollectEvents(contract))
        {
            EmitEvent(builder, indent, eventSymbol);
            builder.AppendLine();
        }

        foreach (var method in CollectMethods(contract))
        {
            EmitMethod(builder, indent, contract, method);
            builder.AppendLine();
        }

        builder.Append(indent);
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static IEnumerable<IMethodSymbol> CollectMethods(INamedTypeSymbol contract)
    {
        var signatures = new HashSet<string>(StringComparer.Ordinal);

        foreach (var symbol in contract.GetMembers().OfType<IMethodSymbol>())
        {
            if (symbol.MethodKind != MethodKind.Ordinary)
            {
                continue;
            }

            var key = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            if (signatures.Add(key))
            {
                yield return symbol;
            }
        }

        foreach (var inherited in contract.AllInterfaces)
        {
            foreach (var symbol in inherited.GetMembers().OfType<IMethodSymbol>())
            {
                if (symbol.MethodKind != MethodKind.Ordinary)
                {
                    continue;
                }

                var key = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                if (signatures.Add(key))
                {
                    yield return symbol;
                }
            }
        }
    }

    private static IEnumerable<IPropertySymbol> CollectProperties(INamedTypeSymbol contract)
