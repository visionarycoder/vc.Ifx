    private static void EmitProperty(StringBuilder builder, string indent, IPropertySymbol property, bool explicitImplementation)
    {
        var propertyType = property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var propertyName = EscapeIdentifier(property.Name);
        var declaringType = property.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        if (property.IsIndexer)
        {
            builder.Append(indent);
            builder.Append("    public ");
            builder.Append(propertyType);
            builder.Append(" this[");
            builder.Append(BuildParameterDeclarationList(property.Parameters));
            builder.AppendLine("]");
            builder.Append(indent);
            builder.AppendLine("    {");

            if (property.GetMethod != null)
            {
                builder.Append(indent);
                builder.Append("        get => innerService[");
                builder.Append(BuildParameterInvocationList(property.Parameters));
                builder.AppendLine("]; ");
            }

            if (property.SetMethod != null)
            {
                builder.Append(indent);
                builder.Append("        set => innerService[");
                builder.Append(BuildParameterInvocationList(property.Parameters));
                builder.AppendLine("] = value;");
            }

            builder.Append(indent);
            builder.AppendLine("    }");
            return;
        }

        builder.Append(indent);
        builder.Append(explicitImplementation ? "    " : "    public ");
        builder.Append(propertyType);
        builder.Append(' ');
        if (explicitImplementation) { builder.Append(declaringType).Append('.'); }
        builder.Append(propertyName);
        builder.AppendLine();
        builder.Append(indent);
        builder.AppendLine("    {");

        if (property.GetMethod != null)
        {
            builder.Append(indent);
            builder.Append("        get => ((").Append(declaringType).Append(")innerService).");
            builder.Append(propertyName);
            builder.AppendLine(";");
        }

        if (property.SetMethod != null)
        {
            builder.Append(indent);
            builder.Append("        set => ((").Append(declaringType).Append(")innerService).");
            builder.Append(propertyName);
            builder.AppendLine(" = value;");
        }

        builder.Append(indent);
        builder.AppendLine("    }");
    }

    private static void EmitEvent(StringBuilder builder, string indent, IEventSymbol eventSymbol)
    {
        var eventType = eventSymbol.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var eventName = EscapeIdentifier(eventSymbol.Name);

        builder.Append(indent);
        builder.Append("    public event ");
        builder.Append(eventType);
        builder.Append(' ');
        builder.Append(eventName);
        builder.AppendLine();
        builder.Append(indent);
        builder.AppendLine("    {");
        builder.Append(indent);
        builder.Append("        add => innerService.");
        builder.Append(eventName);
        builder.AppendLine(" += value;");
        builder.Append(indent);
        builder.Append("        remove => innerService.");
        builder.Append(eventName);
        builder.AppendLine(" -= value;");
        builder.Append(indent);
        builder.AppendLine("    }");
    }

    private static void EmitMethod(StringBuilder builder, string indent, INamedTypeSymbol contract, IMethodSymbol method)
    {
        var returnType = method.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var methodName = EscapeIdentifier(method.Name);
        var parameters = BuildParameterDeclarationList(method.Parameters);
        var callArguments = BuildParameterInvocationList(method.Parameters);
        var typeParameterList = BuildTypeParameterList(method);
        var constraints = BuildConstraints(method);

        var isTask = IsTask(method.ReturnType, out var taskTypeArgument);
        var isValueTask = IsValueTask(method.ReturnType, out var valueTaskTypeArgument);
        var isAsync = isTask || isValueTask;

        builder.Append(indent);
        builder.Append("    public ");
        if (isAsync)
        {
            builder.Append("async ");
        }

        builder.Append(returnType);
        builder.Append(' ');
        builder.Append(methodName);
        builder.Append(typeParameterList);
        builder.Append('(');
        builder.Append(parameters);
        builder.Append(')');

        if (!string.IsNullOrWhiteSpace(constraints))
        {
            builder.AppendLine();
            builder.Append(indent);
            builder.Append("    ");
            builder.Append(constraints);
        }

        builder.AppendLine();
        builder.Append(indent);
        builder.AppendLine("    {");
        builder.Append(indent);
        builder.Append("        using var activity = activitySource.StartActivity(");
        builder.Append(ToLiteral(contract.Name + "." + method.Name));
        builder.AppendLine(", ActivityKind.Internal);");
        builder.Append(indent);
        builder.AppendLine("        activity?.SetTag(\"component.layer\", \"Boundary\");");
        builder.Append(indent);
        builder.Append("        activity?.SetTag(\"component.contract\", ");
        builder.Append(ToLiteral(contract.ToDisplayString()));
        builder.AppendLine(");");
        builder.Append(indent);
        builder.Append("        activity?.SetTag(\"operation.name\", ");
        builder.Append(ToLiteral(method.Name));
        builder.AppendLine(");");

        var serviceRequestParameter = FindServiceRequestParameter(method.Parameters);
        if (serviceRequestParameter != null)
        {
            var parameterName = EscapeIdentifier(serviceRequestParameter.Name);

            builder.Append(indent);
            builder.Append("        if (");
            builder.Append(parameterName);
            builder.AppendLine(" != null)");
            builder.Append(indent);
            builder.AppendLine("        {");
            builder.Append(indent);
            builder.Append("            activity?.SetTag(\"message.correlation_id\", ");
            builder.Append(parameterName);
            builder.AppendLine(".CorrelationId);");
            builder.Append(indent);
            builder.Append("            activity?.SetTag(\"message.id\", ");
            builder.Append(parameterName);
            builder.AppendLine(".MessageId);");
            builder.Append(indent);
            builder.Append("            logger.LogInformation(\"OpenTelemetry boundary metadata for {Contract}.{Operation}. CorrelationId={CorrelationId}, MessageId={MessageId}\", activity?.GetTagItem(\"component.contract\"), activity?.GetTagItem(\"operation.name\"), ");
            builder.Append(parameterName);
            builder.Append(".CorrelationId, ");
            builder.Append(parameterName);
            builder.AppendLine(".MessageId);");
            builder.Append(indent);
            builder.AppendLine("        }");
        }

        builder.Append(indent);
        builder.AppendLine("        try");
        builder.Append(indent);
        builder.AppendLine("        {");

        if (method.ReturnsVoid)
        {
            builder.Append(indent);
            builder.Append("            innerService.");
            builder.Append(methodName);
            builder.Append(typeParameterList);
            builder.Append('(');
            builder.Append(callArguments);
            builder.AppendLine(");");
            builder.Append(indent);
            builder.AppendLine("            activity?.SetStatus(ActivityStatusCode.Ok);");
            builder.Append(indent);
            builder.AppendLine("            return;");
        }
        else if (isTask && taskTypeArgument == null)
        {
            builder.Append(indent);
            builder.Append("            await innerService.");
            builder.Append(methodName);
            builder.Append(typeParameterList);
            builder.Append('(');
            builder.Append(callArguments);
            builder.AppendLine(").ConfigureAwait(false);");
            builder.Append(indent);
            builder.AppendLine("            activity?.SetStatus(ActivityStatusCode.Ok);");
            builder.Append(indent);
            builder.AppendLine("            return;");
        }
        else if (isTask && taskTypeArgument != null)
        {
            builder.Append(indent);
            builder.Append("            var result = await innerService.");
            builder.Append(methodName);
            builder.Append(typeParameterList);
            builder.Append('(');
            builder.Append(callArguments);
            builder.AppendLine(").ConfigureAwait(false);");
            builder.Append(indent);
            builder.AppendLine("            activity?.SetStatus(ActivityStatusCode.Ok);");
            builder.Append(indent);
            builder.AppendLine("            return result;");
        }
        else if (isValueTask && valueTaskTypeArgument == null)
        {
            builder.Append(indent);
            builder.Append("            await innerService.");
            builder.Append(methodName);
            builder.Append(typeParameterList);
            builder.Append('(');
            builder.Append(callArguments);
            builder.AppendLine(").ConfigureAwait(false);");
            builder.Append(indent);
            builder.AppendLine("            activity?.SetStatus(ActivityStatusCode.Ok);");
            builder.Append(indent);
            builder.AppendLine("            return;");
        }
        else if (isValueTask && valueTaskTypeArgument != null)
        {
            builder.Append(indent);
            builder.Append("            var result = await innerService.");
            builder.Append(methodName);
            builder.Append(typeParameterList);
            builder.Append('(');
            builder.Append(callArguments);
            builder.AppendLine(").ConfigureAwait(false);");
            builder.Append(indent);
            builder.AppendLine("            activity?.SetStatus(ActivityStatusCode.Ok);");
            builder.Append(indent);
            builder.AppendLine("            return result;");
        }
        else
        {
            builder.Append(indent);
            builder.Append("            var result = innerService.");
            builder.Append(methodName);
            builder.Append(typeParameterList);
            builder.Append('(');
            builder.Append(callArguments);
            builder.AppendLine(");");
            builder.Append(indent);
            builder.AppendLine("            activity?.SetStatus(ActivityStatusCode.Ok);");
            builder.Append(indent);
            builder.AppendLine("            return result;");
        }

        builder.Append(indent);
        builder.AppendLine("        }");
        builder.Append(indent);
        builder.AppendLine("        catch (Exception ex)");
        builder.Append(indent);
        builder.AppendLine("        {");
        builder.Append(indent);
        builder.AppendLine("            activity?.SetStatus(ActivityStatusCode.Error, ex.Message);");
        builder.Append(indent);
        // RecordException() is not available in System.Diagnostics.Activity
        builder.Append(indent);
        builder.AppendLine("            logger.LogError(ex, \"OpenTelemetry boundary call failed for {Contract}.{Operation}\", activity?.GetTagItem(\"component.contract\"), activity?.GetTagItem(\"operation.name\"));");
        builder.Append(indent);
        builder.AppendLine("            throw;");
        builder.Append(indent);
        builder.AppendLine("        }");
        builder.Append(indent);
        builder.AppendLine("    }");
    }

    private static IParameterSymbol? FindServiceRequestParameter(ImmutableArray<IParameterSymbol> parameters)
    {
        foreach (var parameter in parameters)
        {
            if (IsServiceRequestType(parameter.Type))
            {
                return parameter;
            }
        }

        return null;
    }

    private static bool IsServiceRequestType(ITypeSymbol typeSymbol)
    {
        var namedType = typeSymbol as INamedTypeSymbol;
        while (namedType != null)
        {
            if (string.Equals(namedType.ToDisplayString(), ServiceRequestFullName, StringComparison.Ordinal))
            {
                return true;
            }

            namedType = namedType.BaseType;
        }

        return false;
    }

    private static string BuildTypeParameterList(IMethodSymbol method)
    {
        if (method.TypeParameters.Length == 0)
        {
            return string.Empty;
        }

        return "<" + string.Join(", ", method.TypeParameters.Select(parameter => parameter.Name)) + ">";
    }

    private static string BuildConstraints(IMethodSymbol method)
    {
        var clauses = new List<string>();

        foreach (var typeParameter in method.TypeParameters)
        {
            var constraints = new List<string>();

            if (typeParameter.HasReferenceTypeConstraint)
            {
                constraints.Add("class");
            }

            if (typeParameter.HasUnmanagedTypeConstraint)
            {
                constraints.Add("unmanaged");
            }
            else if (typeParameter.HasValueTypeConstraint)
            {
                constraints.Add("struct");
            }

            foreach (var constraintType in typeParameter.ConstraintTypes)
            {
                constraints.Add(constraintType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
            }

            if (typeParameter.HasConstructorConstraint)
            {
                constraints.Add("new()");
            }

            if (constraints.Count > 0)
            {
                clauses.Add("where " + typeParameter.Name + " : " + string.Join(", ", constraints));
            }
        }

        return string.Join(" ", clauses);
    }

    private static string BuildParameterDeclarationList(ImmutableArray<IParameterSymbol> parameters)
    {
        return string.Join(", ", parameters.Select(p => BuildParameterDeclaration(p)));
    }

    private static string BuildParameterDeclaration(IParameterSymbol parameter)
    {
        var builder = new StringBuilder();

        if (parameter.IsParams)
        {
            builder.Append("params ");
        }
        else if (parameter.RefKind == RefKind.Ref)
        {
            builder.Append("ref ");
        }
        else if (parameter.RefKind == RefKind.Out)
        {
            builder.Append("out ");
        }
        else if (parameter.RefKind == RefKind.In)
        {
            builder.Append("in ");
        }

        builder.Append(parameter.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
        builder.Append(' ');
        builder.Append(EscapeIdentifier(parameter.Name));

        return builder.ToString();
    }

    private static string BuildParameterInvocationList(ImmutableArray<IParameterSymbol> parameters)
    {
        return string.Join(", ", parameters.Select(p => BuildParameterInvocation(p)));
    }

    private static string BuildParameterInvocation(IParameterSymbol parameter)
    {
        var prefix = string.Empty;

        if (parameter.RefKind == RefKind.Ref)
        {
            prefix = "ref ";
        }
        else if (parameter.RefKind == RefKind.Out)
        {
            prefix = "out ";
        }
        else if (parameter.RefKind == RefKind.In)
        {
            prefix = "in ";
        }

        return prefix + EscapeIdentifier(parameter.Name);
    }

    private static bool IsTask(ITypeSymbol typeSymbol, out ITypeSymbol? typeArgument)
    {
        typeArgument = null;

        if (!(typeSymbol is INamedTypeSymbol namedType))
        {
            return false;
        }

        if (namedType.ContainingNamespace.ToDisplayString() != "System.Threading.Tasks")
        {
            return false;
        }

        if (namedType.Name != "Task")
        {
            return false;
        }

        if (namedType.TypeArguments.Length == 1)
        {
            typeArgument = namedType.TypeArguments[0];
        }

        return true;
    }

    private static bool IsValueTask(ITypeSymbol typeSymbol, out ITypeSymbol? typeArgument)
    {
        typeArgument = null;

        if (!(typeSymbol is INamedTypeSymbol namedType))
        {
            return false;
        }

        if (namedType.ContainingNamespace.ToDisplayString() != "System.Threading.Tasks")
        {
            return false;
        }

        if (namedType.Name != "ValueTask")
        {
            return false;
        }

        if (namedType.TypeArguments.Length == 1)
        {
            typeArgument = namedType.TypeArguments[0];
        }

        return true;
    }

    private static string GetInterceptorName(INamedTypeSymbol contract, string suffix)
    {
        var nameBuilder = new StringBuilder(contract.Name.Replace("`", string.Empty));

        if (contract.TypeArguments.Length > 0)
        {
            foreach (var typeArgument in contract.TypeArguments)
            {
                nameBuilder.Append('_');
                nameBuilder.Append(typeArgument.Name.Replace("`", string.Empty));
            }
        }

        nameBuilder.Append(suffix);
        return nameBuilder.ToString();
    }

    private static string EscapeIdentifier(string identifier)
    {
        if (SyntaxFacts.GetKeywordKind(identifier) != SyntaxKind.None)
        {
            return "@" + identifier;
        }

        return identifier;
    }

    private static string ToLiteral(string value)
    {
        var builder = new StringBuilder(value.Length + 2);
        builder.Append('"');

        foreach (var character in value)
        {
            switch (character)
            {
                case '\\':
                    builder.Append("\\\\");
                    break;
                case '"':
                    builder.Append("\\\"");
                    break;
                case '\r':
                    builder.Append("\\r");
                    break;
                case '\n':
                    builder.Append("\\n");
                    break;
                case '\t':
                    builder.Append("\\t");
                    break;
                default:
                    builder.Append(character);
                    break;
            }
        }

        builder.Append('"');
        return builder.ToString();
    }

