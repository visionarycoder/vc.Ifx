namespace Wa.Wsdot.Fin.Idl.Ifx.Proxies.Interceptors.Status;

/// <summary>
/// Represents the status of a method invocation.
/// </summary>
public enum Status
{
    /// <summary>
    /// The invocation has started.
    /// </summary>
    Started,

    /// <summary>
    /// The invocation has completed successfully.
    /// </summary>
    Completed,

    /// <summary>
    /// The invocation has failed with an exception.
    /// </summary>
    Failed
}
